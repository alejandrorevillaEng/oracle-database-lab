ALTER SESSION SET CONTAINER = FREEPDB1;
SET LINESIZE 170 FEEDBACK OFF
COLUMN tipo FORMAT A12
COLUMN rowid_ext FORMAT A22
COLUMN rowid_res FORMAT A22
SELECT DBMS_ROWID.ROWID_TYPE(ROWID) AS tipo,
       ROWIDTOCHAR(ROWID) AS rowid_ext,
       ROWIDTOCHAR(DBMS_ROWID.ROWID_TO_RESTRICTED(ROWID, 0)) AS rowid_res,
       DBMS_ROWID.ROWID_BLOCK_NUMBER(ROWID) AS bloq_ext_sin,
       DBMS_ROWID.ROWID_BLOCK_NUMBER(ROWID, 'BIGFILE') AS bloq_ext_big,
       DBMS_ROWID.ROWID_BLOCK_NUMBER(DBMS_ROWID.ROWID_TO_RESTRICTED(ROWID, 0)) AS bloq_res_sin,
       DBMS_ROWID.ROWID_BLOCK_NUMBER(DBMS_ROWID.ROWID_TO_RESTRICTED(ROWID, 0), 'BIGFILE') AS bloq_res_big
  FROM admin_academia.aca_estudiantes WHERE estudiante_id = 101;
EXIT
